from sf import *
from reports.cohort_analysis import _build_base_tables, CANON_STUDIO, XWALK, DATAMART
c=conn()
_build_base_tables(c,'2021-01')
# extended sales with product detail, same filters as COH_SALES
execute_sql(c,f"""
CREATE OR REPLACE TEMPORARY TABLE MKT_SALES AS
SELECT x.GLOBAL_CLIENT_KEY GCK, s.SALE_DATE, s.NET_PAYMENTAMT_LOCAL NET, s.IS_AUTOPAY, s.IS_INTRO_OFFER, s.ITEM_TYPE,
       s.REVENUE_CATEGORY, s.PRODUCT_DESCRIPTION, s.PO_CAPACITY_COUNT, s.UNIT_PRICE, s.PROMOTION_NAME,
       {CANON_STUDIO}(s.STUDIO_NAME) STUDIO
FROM {DATAMART}.MART_SALES_DETAILS s
JOIN {XWALK} x ON x.STUDIO_ID=s.STUDIO_ID AND x.CLIENT_ID=s.CLIENT_ID
WHERE s.SALE_DATE>='2021-01-01' AND s.SALE_DATE<=CURRENT_DATE()
  AND (s.PRODUCT_DESCRIPTION != 'ClassPass' OR s.PRODUCT_DESCRIPTION IS NULL)
  AND (s.ITEM_TYPE != 'Pricing Option' OR s.PAYMENT_REF_NO IS NOT NULL OR s.IS_RETURN = 1)
  AND s.CATEGORY_ID NOT IN (-6,-64,-73)
  AND COALESCE(s.NET_PAYMENTAMT_LOCAL,0) <> 0
  AND x.GLOBAL_CLIENT_KEY NOT IN (SELECT GCK FROM COH_EXCLUDED_KEYS)
  AND NOT EXISTS (SELECT 1 FROM {DATAMART}.MART_SALES_DETAILS dup
      WHERE dup.PAYMENT_REF_NO=s.PAYMENT_REF_NO AND dup.CLIENT_ID=s.CLIENT_ID AND dup.PRODUCT_ID=s.PRODUCT_ID
        AND dup.SALE_DATE=s.SALE_DATE AND dup.STUDIO_NAME LIKE '%Presidio%' AND s.STUDIO_NAME LIKE '%Marin%' AND s.SALE_DATE<'2025-04-24')
""")
print(q(c,"select count(*), sum(NET) from MKT_SALES"), q(c,"select count(*), sum(NET_SALES) from COH_SALES"))
# 1. client first-purchase record
first=q(c,"""
WITH r AS (SELECT *, ROW_NUMBER() OVER (PARTITION BY GCK ORDER BY SALE_DATE, IS_INTRO_OFFER DESC, NET DESC) rn FROM MKT_SALES WHERE NET>0)
SELECT r.GCK, r.SALE_DATE FIRST_DATE, r.STUDIO FIRST_STUDIO, r.PRODUCT_DESCRIPTION FIRST_PRODUCT, r.IS_INTRO_OFFER FIRST_INTRO,
       r.REVENUE_CATEGORY FIRST_CAT, r.ITEM_TYPE FIRST_ITEM, r.NET FIRST_NET, cl.TRUE_FIRST_SALE_DATE, cl.REFERRED_BY, cl.CLASSPASS_STATUS,
       m.FIRST_ACTIVATION
FROM r JOIN COH_CLIENTS cl ON cl.GCK=r.GCK LEFT JOIN COH_MEMBERS m ON m.GCK=r.GCK WHERE rn=1""")
first.to_pickle('first.pkl'); print('first',len(first))
# first visit (any, incl ClassPass) per client
fv=q(c,"select GCK, MIN(CLASS_DATE) FIRST_VISIT, MIN(CASE WHEN CLASSPASS_SOURCE IS NOT NULL THEN CLASS_DATE END) FIRST_CP_VISIT from COH_VISITS group by 1")
fv.to_pickle('firstvisit.pkl'); print('fv',len(fv))
# 2. client-month sales
cm=q(c,"""SELECT GCK, DATE_TRUNC('MONTH',SALE_DATE) M, STUDIO, SUM(NET) NET, SUM(IFF(IS_AUTOPAY=1,NET,0)) NET_AUTOPAY,
   SUM(IFF(IS_INTRO_OFFER=1,NET,0)) NET_INTRO, SUM(IFF(ITEM_TYPE='Retail Product',NET,0)) NET_RETAIL
   FROM MKT_SALES GROUP BY 1,2,3""")
cm.to_pickle('clientmonth.pkl'); print('cm',len(cm))
# 2b. daily sales for first-N-day windows for clients first purchased since 2024
cd=q(c,"""SELECT s.GCK, s.SALE_DATE, SUM(s.NET) NET FROM MKT_SALES s WHERE s.SALE_DATE>='2023-01-01' GROUP BY 1,2""")
cd.to_pickle('clientday.pkl'); print('cd',len(cd))
# 3. client-month visits
vm=q(c,"""SELECT GCK, VISIT_MONTH M, COUNT(*) VISITS, SUM(IFF(CLASSPASS_SOURCE IS NOT NULL,1,0)) CP_VISITS FROM COH_VISITS WHERE CLASS_DATE>='2023-01-01' GROUP BY 1,2""")
vm.to_pickle('visitmonth.pkl'); print('vm',len(vm))
print(q(c,"select CLASSPASS_SOURCE, count(*) from COH_VISITS where CLASS_DATE>='2025-10-01' group by 1"))
# 4. autopay rows
ap=q(c,"""SELECT GCK, SALE_DATE, STUDIO, PRODUCT_DESCRIPTION, REVENUE_CATEGORY, PO_CAPACITY_COUNT, NET, UNIT_PRICE, IS_INTRO_OFFER FROM MKT_SALES
   WHERE IS_AUTOPAY=1 AND ITEM_TYPE='Pricing Option' AND SALE_DATE>='2023-01-01'""")
ap.to_pickle('autopay.pkl'); print('ap',len(ap))
# 5. membership daily official counts by studio-month
mem=q(c,f"""SELECT TO_VARCHAR(DATE,'YYYY-MM') MONTH, {CANON_STUDIO}(STUDIO_NAME) STUDIO,
   SUM(IS_UNIQUE_NEW_MEMBER) NEW_MEMBERS, SUM(IS_UNIQUE_REACTIVATED_MEMBER) REACTIVATED, SUM(IS_UNIQUE_CHURN_MEMBER) CHURNED,
   SUM(IS_UNIQUE_TERMINATED_MEMBER) TERMINATED, SUM(IS_UNIQUE_EXPIRED_MEMBER) EXPIRED,
   SUM(CASE WHEN DATE=LAST_DAY(DATE) THEN IS_UNIQUE_ACTIVE_MEMBER END) ACTIVE_EOM,
   SUM(CASE WHEN DATE=LAST_DAY(DATE) THEN IS_UNIQUE_SUSPENDED_MEMBER END) SUSPENDED_EOM
   FROM {DATAMART}.MART_MEMBERSHIP_DAILY_DETAILS WHERE DATE>='2023-01-01' AND DATE<=CURRENT_DATE() GROUP BY 1,2""")
mem.to_pickle('mem.pkl'); print('mem',len(mem))
# 6. total sales by studio-month-category for context
ss=q(c,"""SELECT DATE_TRUNC('MONTH',SALE_DATE) M, STUDIO, SUM(NET) NET, SUM(IFF(IS_AUTOPAY=1,NET,0)) NET_AUTOPAY, COUNT(DISTINCT GCK) BUYERS FROM MKT_SALES WHERE SALE_DATE>='2023-01-01' GROUP BY 1,2""")
ss.to_pickle('studiomonth.pkl')
print(q(c,"select STUDIO, min(SALE_DATE), max(SALE_DATE), count(*) from MKT_SALES group by 1 order by 2"))
