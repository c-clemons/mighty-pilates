q(c, "select GCK, TRUE_FIRST_SALE_DATE, REFERRED_BY, CLASSPASS_STATUS from COH_CLIENTS").to_pickle('clients.pkl')

# Month-end member roster (active or suspended)
q(c, f"""SELECT x.GLOBAL_CLIENT_KEY GCK, {CANON_STUDIO}(m.STUDIO_NAME) STUDIO, m.DATE, m.PRICING_OPTION_NAME,
  m.MEMBERSHIP_NAME, m.CONTRACT_NAME, m.IS_ACTIVE_MEMBERSHIP, m.IS_SUSPENDED_MEMBERSHIP, m.IS_UNIQUE_ACTIVE_MEMBER,
  m.FIRST_MEMBERSHIP_ACTIVATION_DATE, m.TERMINATION_DATE, m.IS_AUTOPAY
  FROM {DATAMART}.MART_MEMBERSHIP_DAILY_DETAILS m JOIN {XWALK} x ON x.STUDIO_ID=m.STUDIO_ID AND x.CLIENT_ID=m.CLIENT_ID
  WHERE m.DATE=LAST_DAY(m.DATE) AND m.DATE>='2024-01-01' AND m.DATE<=CURRENT_DATE()
    AND (m.IS_ACTIVE_MEMBERSHIP=1 OR m.IS_SUSPENDED_MEMBERSHIP=1)""").to_pickle('memeom.pkl')

# Visits. CLASSPASS_SOURCE is 0/1, never NULL -- test "= 1", not "IS NOT NULL".
VIS = f"""FROM {DATAMART}.MART_VISITS v JOIN {XWALK} x ON x.STUDIO_ID=v.STUDIO_ID AND x.CLIENT_ID=v.CLIENT_ID
  WHERE v.CLASS_DATE<=CURRENT_DATE() AND COALESCE(v.IS_CANCELLED,0)=0 AND COALESCE(v.IS_MISSED,0)=0"""
q(c, f"""SELECT x.GLOBAL_CLIENT_KEY GCK, DATE_TRUNC('MONTH',v.CLASS_DATE) M, COUNT(*) VISITS,
  SUM(IFF(v.CLASSPASS_SOURCE=1,1,0)) CP_VISITS {VIS} AND v.CLASS_DATE>='2021-01-01' GROUP BY 1,2""").to_pickle('visitmonth.pkl')
q(c, f"""SELECT x.GLOBAL_CLIENT_KEY GCK, MIN(v.CLASS_DATE) FIRST_VISIT,
  MIN(IFF(v.CLASSPASS_SOURCE=1,v.CLASS_DATE,NULL)) FIRST_CP_VISIT,
  MIN(IFF(COALESCE(v.CLASSPASS_SOURCE,0)=0,v.CLASS_DATE,NULL)) FIRST_DIRECT_VISIT {VIS} GROUP BY 1""").to_pickle('firstvisit.pkl')
q(c, f"""WITH r AS (SELECT x.GLOBAL_CLIENT_KEY GCK, v.CLASS_DATE, {CANON_STUDIO}(v.STUDIO_NAME) STUDIO,
  COALESCE(v.CLASSPASS_SOURCE,0) CP,
  ROW_NUMBER() OVER (PARTITION BY x.GLOBAL_CLIENT_KEY ORDER BY v.CLASS_DATE, v.VISIT_START_TIME) rn {VIS})
  SELECT GCK, CLASS_DATE, STUDIO, CP FROM r WHERE rn=1""").to_pickle('firstvisit_studio.pkl')

# Machine-class fill by studio-month
q(c, f"""SELECT {CANON_STUDIO}(STUDIO_NAME) STUDIO, TO_VARCHAR(DATE_TRUNC('month',CLASS_DATE),'YYYY-MM') M, COUNT(*) CLASSES,
  SUM(TOTAL_SIGNED_IN) SIGNED_IN, SUM(TOTAL_CAPACITY) CAPACITY FROM {DATAMART}.MART_CLASS_SCHEDULE_INSTANCES
  WHERE CLASS_DATE BETWEEN '2025-01-01' AND '2026-09-30' AND SERVICE_CATEGORY='Machine' AND IS_ONLINE_CLASS=false
    AND HAS_ATTENDANCE_ACTIVITY=true AND TOTAL_CAPACITY>0 GROUP BY 1,2""").to_pickle('fill.pkl')
